def get_last_callable(path):
    """Faithful emulation of kaggle_environments.agent.get_last_callable:
    empty globals (no __file__), agent dir *appended* to sys.path."""
    with open(path) as f:
        code = compile(f.read(), path, "exec")
    env = {}
    sys.path.append(os.path.dirname(path))
    try:
        exec(code, env)
    finally:
        sys.path.pop()
    callables = [v for v in env.values() if callable(v)]
    return callables[-1] if callables else None


def write_agent_dir(policy, out_dir, temperature=0.0, sheep_cash_max=0,
                    sheep_min_day=4, sheep_timeout=96):
    """Write a ready-to-run numpy agent directory for `policy` and verify the
    loader contract statically. Shared by the CLI export and league promotion.

    Module names are suffixed with this export's identity: kg_rules is the
    shared rules mirror (collisions are harmless by design), but obs/actions
    must be unique per export or two of our agents in one process share the
    cached module and the second reads the first's weights."""
    import re
    if sheep_cash_max < 0:
        raise ValueError("sheep_cash_max must be non-negative")
    if sheep_min_day < 0:
        raise ValueError("sheep_min_day must be non-negative")
    if sheep_timeout <= 0:
        raise ValueError("sheep_timeout must be positive")
    os.makedirs(out_dir, exist_ok=True)
    sfx = re.sub(r"\W", "_", os.path.basename(os.path.normpath(out_dir)))
    policy.export_npz(os.path.join(out_dir, "weights.npz"))
    for src, dst in ((os.path.join(_RL, "obs.py"), f"kg_rl_obs_{sfx}.py"),
                     (os.path.join(_RL, "actions.py"), f"kg_rl_actions_{sfx}.py"),
                     (os.path.join(_REPO, "agents", "kg_rules.py"), "kg_rules.py")):
        shutil.copy(src, os.path.join(out_dir, dst))
    main_path = os.path.join(out_dir, "main.py")
    with open(main_path, "w") as f:
        f.write(MAIN_TEMPLATE.replace("{sfx}", sfx)
                .replace("{temp}", repr(float(temperature)))
                .replace("{sheep_cash_max}", repr(int(sheep_cash_max)))
                .replace("{sheep_min_day}", repr(int(sheep_min_day)))
                .replace("{sheep_timeout}", repr(int(sheep_timeout))))
    fn = get_last_callable(main_path)
    assert fn is not None and fn.__name__ == "agent", \
        f"last callable is {fn}, expected the agent"
    return main_path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", default=os.path.join(_RL, "out"))
    ap.add_argument("--sample", type=float, default=0.0,
                    help="softmax sampling temperature baked into the "
                         "export (0 = greedy argmax)")
    ap.add_argument("--sheep-cash-max", type=int, default=0,
                    help="enable the one-sheep option at or below this cash")
    ap.add_argument("--sheep-min-day", type=int, default=4)
    ap.add_argument("--sheep-timeout", type=int, default=96)
    args = ap.parse_args()

    import torch
    from policy import Policy
    import actions as A
    import obs as O

    out_dir = os.path.join(args.out, args.name)

    ck = torch.load(args.ckpt, map_location="cpu", weights_only=False)
    sd = ck["model"]
    if any(k.startswith(("base.", "hands.")) for k in sd):
        # residual and/or multi-head checkpoints: ship raw arrays; the
        # main.py template understands every combination (a plain-Policy
        # load here would silently drop the hand heads -- a different agent)
        import types
        import numpy as np
        sys.path.insert(0, os.path.join(_RL, "tensor_env"))
        from trl_policy import actor_arrays

        if any(k.startswith("base.") for k in sd):
            arrays = actor_arrays(sd, "base.", numpy=True)
            arrays.update({f"d_{k}": v for k, v in
                           actor_arrays(sd, "delta.", numpy=True).items()})
        else:
            arrays = actor_arrays(sd, numpy=True)
        policy = types.SimpleNamespace(
            export_npz=lambda path: np.savez(path, **arrays))
    else:
        hidden = ck.get("hidden", [512, 256])
        policy = Policy(O.OBS_DIM, A.N_FARMER, A.N_MARKET, *hidden)
        # strict=False: pre-value-net checkpoints lack v1/v2 keys, and the
        # value net never ships anyway -- only the policy side is exported.
        policy.load_state_dict(sd, strict=False)
    main_path = write_agent_dir(
        policy, out_dir, temperature=args.sample,
        sheep_cash_max=args.sheep_cash_max,
        sheep_min_day=args.sheep_min_day, sheep_timeout=args.sheep_timeout)
    fn = get_last_callable(main_path)
    from kg_env import KGEnv
    raw = KGEnv(opponent="starter").reset(seed=123)
    act = fn(raw)
    assert isinstance(act, dict) and set(act) == {"farmer", "hands", "market"}, act
    assert act["farmer"] != ["PASS"] or act["market"], \
        "exported agent answers PASS/no-op on the opening state -- suspicious"
    # rl-baseline checkpoints carry global_step/stage; torchrl ones iter/algo
    step = ck.get("global_step", ck.get("iter"))
    step_s = f"{step:,}" if isinstance(step, int) else "?"
    print(f"exported {out_dir}  (ckpt step {step_s}, "
          f"stage {ck.get('stage', ck.get('algo'))})")
    print(f"opening action: {act['farmer']} market {act['market']}")


if __name__ == "__main__":
    main()
