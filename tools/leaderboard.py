"""Render the strategy leaderboard from data/arena.sqlite.

Emits a markdown table into the repo and a self-contained HTML page suitable for
publishing, so collaborators can see which strategies are winning without
running anything themselves. Re-run after every tournament; the same file paths
are overwritten, so a published page keeps its URL.

    python tools/leaderboard.py --run latest
    python tools/leaderboard.py --run latest --html site/leaderboard.html
"""

