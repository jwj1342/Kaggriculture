AXES = ["land", "labour", "produce", "market", "intel", "muck"]


def load(con, run_id):
    ratings = [dict(r) for r in con.execute(
        "SELECT * FROM ratings WHERE run_id=? ORDER BY bt_elo DESC", (run_id,))]
    atoms = {}
    for r in con.execute("SELECT name, atoms, alias FROM agents"):
        try:
            atoms[r["name"]] = (json.loads(r["atoms"] or "{}"), r["alias"])
        except Exception:
            atoms[r["name"]] = ({}, None)
    run = dict(con.execute("SELECT * FROM runs WHERE id=?", (run_id,)).fetchone())
    return run, ratings, atoms


def atom_effects(ratings, atoms):
    """Mean BT-Elo per atom option -- the main effect of each choice."""
    buckets = defaultdict(lambda: defaultdict(list))
    for r in ratings:
        a, _ = atoms.get(r["agent"], ({}, None))
        for ax in AXES:
            if ax in a:
                buckets[ax][a[ax]].append(r["bt_elo"])
    out = {}
    for ax, opts in buckets.items():
        rows = [(opt, statistics.mean(v), len(v)) for opt, v in opts.items() if v]
        rows.sort(key=lambda t: -t[1])
        out[ax] = rows
    return out


def render_md(run, ratings, atoms, effects, top=40):
    L = []
    L.append("# Strategy leaderboard\n")
    L.append(f"Run **#{run['id']}** · `{run['label']}` · {run['kind']} · "
             f"{run['n_agents']:,} strategies · {run['n_episodes']:,} episodes · "
             f"{run['seeds']} seeds/pair · finished {run['finished_at']}\n")
    L.append("Ranked by **Bradley-Terry** strength — the same estimator Kaggle uses "
             "for the final leaderboard. BT-Elo is relative to the median strategy "
             "in the field; +400 means 10:1 odds.\n")
    L.append("> A high win rate with a low median $ means the strategy wins by "
             "denying the shared market rather than by earning. That does score on "
             "the ladder, but it is fragile against opponents who do not feed it.\n")

    L.append(f"## Top {top}\n")
    L.append("| # | BT-Elo | win% | median $ | sd $ | strategy | alias |")
    L.append("|--:|-------:|-----:|---------:|-----:|----------|-------|")
    for i, r in enumerate(ratings[:top], 1):
        _, alias = atoms.get(r["agent"], ({}, None))
        L.append(f"| {i} | {r['bt_elo']:+.0f} | {r['winrate']*100:.0f} | "
                 f"{r['median_money']:,.0f} | {r['sd_money']:,.0f} | "
                 f"`{r['agent']}` | {alias or ''} |")

    L.append("\n## Atom main effects\n")
    L.append("Mean BT-Elo of every strategy carrying each option. This is the "
             "marginal value of the choice, averaged over everything else.\n")
    for ax in AXES:
        if ax not in effects:
            continue
        L.append(f"**{ax}**\n")
        L.append("| option | mean BT-Elo | strategies |")
        L.append("|--------|------------:|-----------:|")
        for opt, mean, n in effects[ax]:
            L.append(f"| `{opt}` | {mean:+.0f} | {n} |")
        L.append("")

    L.append("## Bottom 10\n")
    L.append("| BT-Elo | win% | median $ | strategy |")
    L.append("|-------:|-----:|---------:|----------|")
    for r in ratings[-10:]:
        L.append(f"| {r['bt_elo']:+.0f} | {r['winrate']*100:.0f} | "
                 f"{r['median_money']:,.0f} | `{r['agent']}` |")
    L.append("\n---\n*Generated by `tools/leaderboard.py` from `data/arena.sqlite`.*")
    return "\n".join(L)


