def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="latest")
    ap.add_argument("--top", type=int, default=40)
    ap.add_argument("--md", default="docs/LEADERBOARD.md")
    ap.add_argument("--html", default="site/leaderboard.html")
    args = ap.parse_args()

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(root)
    con = DB.connect()
    run = DB.latest_run(con) if args.run == "latest" else {"id": int(args.run)}
    if not run:
        raise SystemExit("no finished runs in the database")

    run, ratings, atoms = load(con, run["id"])
    if not ratings:
        raise SystemExit(f"run #{run['id']} has no ratings")
    effects = atom_effects(ratings, atoms)

    with open(args.md, "w") as f:
        f.write(render_md(run, ratings, atoms, effects, args.top))
    print(f"wrote {args.md}")
    os.makedirs(os.path.dirname(os.path.abspath(args.html)), exist_ok=True)
    with open(args.html, "w") as f:
        f.write(render_html(run, ratings, atoms, effects, args.top))
    print(f"wrote {args.html}")

    print(f"\nrun #{run['id']}: {run['n_agents']} strategies, {run['n_episodes']:,} episodes")
    for ax in AXES:
        if ax in effects:
            best = effects[ax][0]
            worst = effects[ax][-1]
            print(f"  {ax:8s} best {best[0]:12s} {best[1]:+7.0f}   "
                  f"worst {worst[0]:12s} {worst[1]:+7.0f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
