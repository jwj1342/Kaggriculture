def render_html(run, ratings, atoms, effects, top=40):
    def esc(s):
        return html.escape(str(s))

    best_opt = {ax: rows[0][0] for ax, rows in effects.items() if rows}

    def gene(agent):
        a, _ = atoms.get(agent, ({}, None))
        if not a:
            return f"<code>{esc(agent)}</code>"
        cells = []
        for ax in AXIS_ORDER:
            opt = a.get(ax, "")
            cls = " class='top'" if opt and opt == best_opt.get(ax) else ""
            cells.append(f"<b{cls}>{esc(opt)}</b>")
        return f"<div class='gene'>{''.join(cells)}</div>"

    hi = max((abs(r["bt_elo"]) for r in ratings), default=1.0) or 1.0
    body = []
    for i, r in enumerate(ratings[:top], 1):
        _, alias = atoms.get(r["agent"], ({}, None))
        neg = r["bt_elo"] < 0
        w = 4 + 96 * abs(r["bt_elo"]) / hi
        body.append(
            f"<tr><td class='rk'>{i}</td>"
            f"<td class='el {'m' if neg else 'p'}'><span class='elo{' m' if neg else ''}'>"
            f"<i style='width:{w:.1f}%'></i><span>{r['bt_elo']:+.0f}</span></span></td>"
            f"<td class='n num'>{r['winrate']*100:.0f}%</td>"
            f"<td class='n num'>{r['median_money']:,.0f}</td>"
            f"<td class='n num dim'>{r['sd_money']:,.0f}</td>"
            f"<td>{gene(r['agent'])}"
            + (f"<span class='alias'>{esc(alias)}</span>" if alias else "")
            + "</td></tr>")

    cards = []
    for ax in AXIS_ORDER:
        rows = effects.get(ax)
        if not rows:
            continue
        lo = min(v for _, v, _ in rows)
        hi_a = max(v for _, v, _ in rows)
        span = (hi_a - lo) or 1.0
        bars = []
        for opt, mean, n in rows:
            w = 3 + 97 * (mean - lo) / span
            bars.append(
                f"<div class='row'><span class='t'>{esc(opt)}</span>"
                f"<span class='g'><i class='{'m' if mean < 0 else ''}' "
                f"style='width:{w:.1f}%'></i></span>"
                f"<span class='v'>{mean:+.0f} · {n}</span></div>")
        cards.append(
            f"<div class='axis'><h3>{esc(ax)}</h3>"
            f"<p class='cap'>{esc(AXIS_CAPTION.get(ax,''))}</p>{''.join(bars)}</div>")

    tail = []
    for r in ratings[-10:]:
        tail.append(
            f"<tr><td class='el m'>{r['bt_elo']:+.0f}</td>"
            f"<td class='n num'>{r['winrate']*100:.0f}%</td>"
            f"<td class='n num'>{r['median_money']:,.0f}</td>"
            f"<td>{gene(r['agent'])}</td></tr>")

