#!/usr/bin/env python
"""Build agents/monger/: the tape's farm + a MEASURED slicing SELL layer.

    python tools/build_monger.py --tape agents/newlines/n04.py --keep 0.90

Every constant in the sell rule came out of `tools/liquidate.py` on the file
that is live on the ladder (docs/RUNS.md 2026-09-04 continuation eleven), and
each one refuted a plausible alternative:

* The book barely moves over a season (MILK -8..+76, WOOL -7..+59 on seed
  555) because `_town_consume` draws it down every four steps. The loss is
  the INTRA-TURN walk: `_process_market` quotes each unit at the live
  inventory and calls `_refresh_prices` only at the end of the phase. So the
  rule caps the per-turn quantity, and does NOT schedule across days.
* There is no intra-day phase edge to exploit: the pre-market price by
  step % 4, recovered from the snapshots, is flat at 1.00x-1.09x. An earlier
  reading of 2.45x was the tape's own uneven sell schedule confounded with
  season position, not a phase effect.
* The shed does NOT bind: seat-0 occupancy was median 16, p90 50, max 89 of
  100 across 719 steps, and never touched 95. Holding units back to slice
  them is therefore free -- but `_drop_inventories` DISCARDS overflow, so the
  rule still dumps when occupancy gets high.
* Slicing is NOT always right. Measured per-seed gain from slicing was
  NEGATIVE for MELON (-8,466, identical on all five seeds), FERTILIZER and
  WHEAT. MELON has no shop at all -- its only demand is the town centre's
  1/day -- so its book never recovers and the right play is to get there
  before the opponent. Hence the race test below, which is evaluated at
  RUNTIME because it depends on the shop draw: WOOL is a slice when a
  YARN_STORE unlocked (12/day) and a race when none did (1/day).

The race test needs to know how much is still coming, and under a frozen farm
tape that is knowable exactly: the tape's own SELL quantities are its
production. They are embedded per product at build time.
"""

