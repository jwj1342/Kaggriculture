def get_last_callable(path):
    src = open(path).read()
    env = {}
    d = os.path.dirname(os.path.abspath(path))
    sys.path.append(d)
    try:
        exec(src, env)
    finally:
        if d in sys.path:
            sys.path.remove(d)
    cs = [v for v in env.values() if callable(v)]
    return cs[-1] if cs else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tape", default="agents/newlines/n04.py")
    ap.add_argument("--out", default="agents/monger")
    ap.add_argument("--keep", type=float, default=0.90,
                    help="per-turn price retention: sell while the marginal "
                         "unit still fetches this fraction of the opening price")
    ap.add_argument("--shed-hi", type=int, default=85,
                    help="dump everything above this shed load; overflow is "
                         "discarded by _drop_inventories, not carried")
    args = ap.parse_args()

    import tape_t
    tape = os.path.join(_REPO, args.tape) if not os.path.isabs(args.tape) \
        else args.tape
    trace = tape_t.load_trace(tape)
    vol = {}
    for t in trace:
        for o in (t or {}).get("market") or []:
            if o and o[0] == "SELL" and len(o) > 2:
                vol[o[1]] = vol.get(o[1], 0) + int(o[2])
    out_dir = os.path.join(_REPO, args.out)
    os.makedirs(out_dir, exist_ok=True)
    shutil.copy(os.path.join(_REPO, "agents", "kg_rules.py"),
                os.path.join(out_dir, "kg_rules.py"))
    blob = base64.b85encode(zlib.compress(
        json.dumps(trace).encode(), 9)).decode()
    body = (MAIN.replace("KEEPVAL", repr(float(args.keep)))
            .replace("SHEDHI", repr(int(args.shed_hi)))
            .replace("VOLJSON", json.dumps(vol).replace('"', '\\"'))
            .replace("TAPEBLOB", blob))
    path = os.path.join(out_dir, "main.py")
    open(path, "w").write(body)

    fn = get_last_callable(path)
    assert fn is not None and fn.__name__ == "agent", f"last callable {fn}"
    print(f"wrote {path}  (tape {os.path.relpath(tape, _REPO)}, "
          f"{len(trace)} turns, keep={args.keep}, shed_hi={args.shed_hi})")
    print(f"tape season volume: "
          + ", ".join(f"{k} {v}" for k, v in sorted(vol.items(),
                                                    key=lambda kv: -kv[1])))


if __name__ == "__main__":
    main()
