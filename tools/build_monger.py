import kg_rules as _R

_TAPE = _js.loads(_zl.decompress(_b64.b85decode("TAPEBLOB")).decode())
_KEEP = KEEPVAL
_SHED_HI = SHEDHI
_STEPS = len(_TAPE)
_PASS = {"farmer": ["PASS"], "hands": [], "market": []}
_SINGLE = {s for s, v in _R.SHOPS.items() if len(v) == 1} if hasattr(
    _R, "SHOPS") else set()
_SHOPS = getattr(_R, "SHOPS", {})
_CENTRE = [p for p in _R.PRODUCTS if p != "FERTILIZER"]


def _cons_per_turn(obs, item):
    """Units of `item` the town absorbs per turn, from the CURRENT shop draw.

    Shops keep unlocking, so this understates future demand -- which biases
    the race test toward racing, i.e. toward the behaviour the measurement
    says is safe (cleo's static layer already wins the melon race)."""
    shops = ((obs.get("town") or {}).get("unlocked_shops") or [])
    per_day = 0.0
    for s in shops:
        prods = _SHOPS.get(s) or []
        if item in prods:
            per_day += 6.0 * (2.0 if len(prods) == 1 else 1.0)
    if item in _CENTRE:
        per_day += 1.0
    return per_day / 24.0


def _depth(item, inv, keep):
    """How many units can go out this turn before the marginal price falls
    below `keep` of the opening price. The walk is what costs money."""
    p0 = _R.market_price(item, inv)
    if p0 <= 1:
        return 1
    lo, hi = 1, 256
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if _R.market_price(item, inv + mid - 1) >= keep * p0:
            lo = mid
        else:
            hi = mid - 1
    return max(1, lo)


def _sells(obs):
    """RE-TIME the tape's own sells. Never add one, never bring one forward.

    The first version sold anything sitting in the shed and lost 60k a game:
    the tape BUYS wheat and fertilizer as inputs (feed, fertiliser), so a
    layer that sells what it finds destroys the farm's own supply -- measured,
    money 78,949 -> 17,096 and the opponent 50,528 -> 95,002 on seed 555,
    because a farm that eats its inputs also stops competing for the book.
    (`nofeedsell-0902` in data/shards is this same family.)

    So the pending queue is the tape's cumulative SELL quantity minus what we
    have actually sold. A unit can only be sold on the tape's own turn or
    LATER, which is exactly the delay-only intervention the bound measured
    (docs/RUNS.md 2026-09-04 continuation eleven), and the sell set is
    identical to the tape's by construction."""
    inv = (obs.get("market") or {}).get("inventory") or {}
    shed = (obs.get("private") or {}).get("shed") or {}
    step = int(obs.get("step", 0) or 0)
    if step == 0:
        _pend.clear()
    left = max(1, _STEPS - step)
    load = sum(max(0, int(v or 0)) for v in shed.values())
    for o in ((_TAPE[step] or {}).get("market") or []):
        if o and o[0] == "SELL" and len(o) > 2:
            _pend[o[1]] = _pend.get(o[1], 0) + int(o[2])
    out = []
    # highest current price first: the engine settles slots in order, so the
    # most valuable sale must take the earliest slot
    items = [i for i in _pend
             if _pend[i] > 0 and int(shed.get(i, 0) or 0) > 0]
    items.sort(key=lambda i: -_R.market_price(i, int(inv.get(i, 10000) or 0)))
    for item in items:
        want = min(_pend[item], int(shed[item] or 0))
        iv = int(inv.get(item, 10000) or 0)
        rate = _cons_per_turn(obs, item)
        if _pend[item] > rate * left or load >= _SHED_HI:
            qty = want          # race, or the shed is about to discard
        else:
            pace = int(_m.ceil(_pend[item] / float(left)))
            qty = min(want, max(_depth(item, iv, _KEEP), pace))
        if qty > 0:
            out.append(["SELL", item, int(qty)])
            _pend[item] -= int(qty)
    return out


_pend = {}


def _act(obs):
    i = int(obs.get("step", 0) or 0)
    if not (0 <= i < _STEPS):
        return _PASS
    t = _TAPE[i] or {}
    buys = [o for o in (t.get("market") or []) if o and o[0] != "SELL"]
    market = (buys + _sells(obs))[:getattr(_R, "MAX_ORDERS", 10)]
    return {"farmer": list(t.get("farmer") or ["PASS"]),
            "hands": [list(h) for h in (t.get("hands") or [])],
            "market": market}


def agent(obs, config=None):
    try:
        return _act(obs)
    except Exception:
        return _PASS
